// The hardware quadratic term truncates the partial products separately.
inline uint32_t sfu_square(uint32_t x) {
  uint32_t result = 0;
  for (unsigned i = 0; i < 17; ++i)
    if (x & (1u << i)) result += x >> (18 - i);
  return result >> 1;
}

inline uint32_t pack_sfu(uint32_t sign, int exponent, uint32_t significand) {
  if (significand == 0x1000000) {
    significand >>= 1;
    ++exponent;
  }
  if (exponent <= 0 || significand < 0x800000) return sign;
  if (exponent >= 255) return sign | 0x7f800000;
  return sign | (uint32_t(exponent) << 23) | (significand - 0x800000);
}

inline float mufu_rcp(float input) {
  uint32_t x = bits(input), sign = x & 0x80000000;
  unsigned exponent = (x >> 23) & 255, fraction = x & 0x7fffff;
  if (exponent == 255) return value(fraction ? 0x7fffffff : sign);
  // The bare MUFU flushes subnormal inputs and outputs.
  if (!exponent) return value(sign | 0x7f800000);
  unsigned index = fraction >> 16, offset = fraction & 0xffff;
  int64_t p1 = int64_t(sfu_rcp_tab[index][0]) << 13;
  int64_t p2 = int64_t(sfu_rcp_tab[index][1]) * offset;
  int64_t p3 = int64_t(sfu_rcp_tab[index][2]) * sfu_square(offset << 1);
  return value(
      pack_sfu(sign, 253 - int(exponent), (p1 + p2 + p3 + 0x47e7) >> 15));
}

inline float mufu_ex2(float input) {
  uint32_t x = bits(input);
  unsigned exponent = (x >> 23) & 255, fraction = x & 0x7fffff;
  bool negative = x >> 31;
  if (exponent == 255 && fraction) return value(0x7fffffff);
  int power = int(exponent) - 127;
  if (power >= 7) return value(negative ? 0 : 0x7f800000);
  uint32_t fixed = 0;
  if (exponent) {
    uint32_t significand = fraction | 0x800000;
    if (power >= 0)
      fixed = significand << power;
    else if (power > -32)
      fixed = significand >> -power;
  }
  int integral = fixed >> 23;
  fraction = fixed & 0x7fffff;
  if (negative) {
    integral = -integral;
    if (fraction) {
      --integral;
      fraction = ~fraction & 0x7fffff;
    }
  }
  unsigned index = fraction >> 17, offset = fraction & 0x1ffff;
  int64_t p1 = int64_t(sfu_ex2_tab[index][0]) << 13;
  int64_t p2 = int64_t(sfu_ex2_tab[index][1]) * offset;
  int64_t p3 = int64_t(sfu_ex2_tab[index][2]) * sfu_square(offset);
  return value(pack_sfu(0, integral + 127, (p1 + p2 + p3 + 0x77e2) >> 15));
}

inline float flush_subnormal(float input) {
  uint32_t x = bits(input);
  return value((x & 0x7f800000) ? x : x & 0x80000000);
}

// Surrounding scaling follows the CUDA 12.8 sm_90a PTX-to-SASS lowering.
inline float ex2(float input, bool ftz) {
  if (!ftz && input < -126.f) {
    float half = mufu_ex2(input * .5f);
    return half * half;
  }
  return mufu_ex2(input);
}

inline float rcp(float input, bool ftz) {
  if (ftz) return mufu_rcp(input);
  float magnitude = std::fabs(input);
  float scale = magnitude < 0x1p-126f  ? 0x1p24f
                : magnitude > 0x1p126f ? .25f
                                       : 1.f;
  return mufu_rcp(input * scale) * scale;
}

inline float divide(float a, float b, bool full, bool ftz) {
  if (ftz) {
    a = flush_subnormal(a);
    b = flush_subnormal(b);
  }
  float magnitude = std::fabs(b);
  float scale = magnitude < 0x1p-126f          ? 0x1p24f
                : full && magnitude > 0x1p126f ? .25f
                                               : 1.f;
  float result = (a * scale) * mufu_rcp(b * scale);
  return ftz ? flush_subnormal(result) : result;
}

